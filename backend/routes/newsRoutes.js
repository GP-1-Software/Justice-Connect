/**
 * GET /api/news
 * Get Palestinian judiciary news
 */
router.get('/', async (req, res) => {
  try {
    const { limit = 10 } = req.query;
    const news = await scrapeNews();
    
    // Limit results
    const limitedNews = news.slice(0, parseInt(limit));
    
    res.json({
      success: true,
      data: limitedNews,
      count: limitedNews.length,
      timestamp: new Date().toISOString()
    });
  } catch (error) {
    console.error('Error in news route:', error);
    res.status(500).json({
      success: false,
      error: 'Failed to fetch news',
      message: error.message
    });
  }
});

/**
 * GET /api/news/:id
 * Get specific news article by ID
 */
router.get('/:id', async (req, res) => {
  try {
    const { id } = req.params;
    const news = await scrapeNews();
    const article = news.find(item => item.id === parseInt(id));
    
    if (!article) {
      return res.status(404).json({
        success: false,
        error: 'Article not found'
      });
    }
    
    res.json({
      success: true,
      data: article
    });
  } catch (error) {
    console.error('Error fetching article:', error);
    res.status(500).json({
      success: false,
      error: 'Failed to fetch article',
      message: error.message
    });
  }
});

export default router;
